#!/usr/bin/env node
// Local source inventory only: no app imports, environment loading or network calls.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputRoot = 'docs/modules';
const mode = process.argv[2];
if (!['--write', '--check'].includes(mode) || process.argv.length !== 3) {
  console.error('Usage: node scripts/module-map.mjs --write | --check');
  process.exit(2);
}
const errors = [];
const fail = (message) => errors.push(message);
const read = (file) => readFileSync(path.join(root, file), 'utf8');
const json = (file) => {
  try { return JSON.parse(read(file)); }
  catch { throw new Error(`Cannot parse ${file} as JSON`); }
};
const catalog = json(`${outputRoot}/catalog.json`);
const groups = { apps: 'Applications', packages: 'Shared packages', extensions: 'Shopify extensions', tooling: 'Nested support packages' };
if (catalog.schemaVersion !== 1 || !Array.isArray(catalog.modules) || !Array.isArray(catalog.storefrontDomains)) {
  throw new Error('Unsupported module catalog schema');
}
if (!/^\d{4}-\d{2}-\d{2}$/.test(catalog.reviewedOn)) fail('reviewedOn must be an ISO date');

const safePath = (file) => typeof file === 'string' && file !== '' && !path.isAbsolute(file)
  && !file.split('/').some((part) => part === '..' || part === '.' || part === '');
const sourceExists = (file) => {
  if (!safePath(file) || !existsSync(path.join(root, file))) fail(`Missing or unsafe source path: ${file}`);
};
const tracked = execFileSync('git', [
  'ls-files', '--cached', '--others', '--exclude-standard', '--',
  'apps/**/package.json', 'packages/**/package.json',
  'apps/**/shopify.extension.toml',
], { cwd: root, encoding: 'utf8' }).trim().split('\n').filter(Boolean);
const discoveredRoots = new Set(tracked.map((file) => path.posix.dirname(file)));
const documentedRoots = new Set();
const outputFiles = new Map();
const cardPath = (module) => `${outputRoot}/${module.group}/${path.posix.basename(module.path)}.md`;
const link = (from, target, label = path.posix.basename(target)) =>
  `[${label}](${path.posix.relative(path.posix.dirname(from), target) || './'})`;
const sourceLink = (from, target, label = target) => link(from, target, label);
const escapeCell = (value) => value.replaceAll('|', '\\|').replaceAll('\n', ' ');
const header = (title) => `<!-- Generated by scripts/module-map.mjs; edit docs/modules/catalog.json, then pnpm docs:modules. -->\n\n# ${title}\n\n`;
const write = (file, text) => {
  if (outputFiles.has(file)) fail(`Duplicate generated path: ${file}`);
  outputFiles.set(file, text);
};
const packageInfo = new Map();
const packageNames = new Map();
for (const module of catalog.modules) {
  if (!groups[module.group]) fail(`Unknown group for ${module.path}`);
  if (documentedRoots.has(module.path)) fail(`Duplicate module root: ${module.path}`);
  documentedRoots.add(module.path);
  sourceExists(module.path);
  for (const key of ['label', 'purpose', 'scope', 'progress', 'next']) {
    if (typeof module[key] !== 'string' || !module[key].trim()) fail(`Missing ${key}: ${module.path}`);
  }
  if (!Array.isArray(module.evidence) || module.evidence.length === 0) fail(`Missing evidence: ${module.path}`);
  else module.evidence.forEach(sourceExists);
  if (existsSync(path.join(root, module.path, 'package.json'))) {
    const pkg = json(`${module.path}/package.json`);
    if (typeof pkg.name !== 'string' || !pkg.name) fail(`Missing package name: ${module.path}`);
    else if (packageNames.has(pkg.name)) fail(`Duplicate package name: ${pkg.name} (${packageNames.get(pkg.name)}, ${module.path})`);
    else packageNames.set(pkg.name, module.path);
    packageInfo.set(module.path, pkg);
  }
}
for (const file of discoveredRoots) if (!documentedRoots.has(file)) fail(`Undocumented module root: ${file}`);
for (const file of documentedRoots) if (!discoveredRoots.has(file)) fail(`Module root has no package or extension manifest: ${file}`);

// Workspace membership comes from the current simple pnpm glob list. Reject
// unsupported syntax rather than silently calling a nested tool a workspace app.
const workspaceLines = read('pnpm-workspace.yaml').split('\n').map((line) => line.trim()).filter((line) => line && !line.startsWith('#'));
if (workspaceLines.shift() !== 'packages:') fail('Unsupported pnpm workspace configuration');
const workspacePatterns = workspaceLines.map((line) => {
  const match = /^-\s+["']?([a-zA-Z0-9_/*-]+)["']?$/.exec(line);
  if (!match) { fail('Unsupported pnpm workspace pattern'); return /^$/; }
  return new RegExp(`^${match[1].split('*').join('[^/]+')}$`);
});
const isWorkspace = (module) => packageInfo.has(module.path) && workspacePatterns.some((pattern) => pattern.test(module.path));
const byName = new Map(catalog.modules.filter((module) => packageInfo.has(module.path)).map((module) => [packageInfo.get(module.path).name, module]));
const dependencies = (module) => {
  const pkg = packageInfo.get(module.path) ?? {};
  return [...new Set(['dependencies', 'devDependencies', 'optionalDependencies', 'peerDependencies']
    .flatMap((field) => Object.keys(pkg[field] ?? {})).filter((name) => byName.has(name)))].sort().map((name) => byName.get(name));
};

for (const module of catalog.modules) {
  const file = cardPath(module);
  const pkg = packageInfo.get(module.path);
  const membership = isWorkspace(module) ? 'pnpm workspace member' : pkg ? 'Nested package outside the root workspace' : 'Extension without a package.json';
  const uses = dependencies(module);
  const usedBy = catalog.modules.filter((other) => dependencies(other).includes(module));
  const parentModule = catalog.modules.filter((other) => module.path.startsWith(`${other.path}/`)).sort((a, b) => b.path.length - a.path.length)[0];
  const containedModules = catalog.modules.filter((other) => other.path.startsWith(`${module.path}/`));
  const showRelations = (items) => items.length ? items.map((item) => link(file, cardPath(item), item.label)).join(', ') : 'None declared in the inventoried package manifests.';
  const checks = ['typecheck', 'test', 'test:unit', 'lint'].filter((name) => pkg?.scripts?.[name]);
  let content = header(module.label)
    + `${link(file, `${outputRoot}/README.md`, 'Module map')} · ${sourceLink(file, module.path, 'Source directory')}\n\n`
    + `${module.purpose}\n\n`
    + `**Scope:** ${module.scope}\n\n`
    + `**Placement:** ${membership}${pkg?.name ? `; package \`${pkg.name}\`` : ''}.\n\n`
    + `## Progress\n\n`
    + `Source review recorded **${catalog.reviewedOn}**. ${module.progress}\n\n`
    + `This records source and documentation evidence. It does not establish deployment, external access, service health, or passing tests.\n\n`
    + `**Next review:** ${module.next}\n\n`
    + `## Evidence and entry points\n\n`
    + module.evidence.map((entry) => `- ${sourceLink(file, entry)}`).join('\n') + '\n\n';
  if (module.path === 'apps/storefront') {
    content += `Start with the ${link(file, `${outputRoot}/storefront/README.md`, 'storefront domain map')} to find the relevant routes and libraries.\n\n`;
  }
  if (parentModule) content += `**Parent module:** ${link(file, cardPath(parentModule), parentModule.label)}.\n\n`;
  if (containedModules.length) content += `**Contained modules:** ${showRelations(containedModules)}.\n\n`;
  content += `## Declared package relationships\n\n`
    + `**Uses:** ${showRelations(uses)}\n\n**Used by:** ${showRelations(usedBy)}\n\n`
    + `Derived from dependencies, development, optional and peer dependencies in package.json. These are declared relationships, not a complete import graph or proof that a runtime path executes.\n\n`
    + `## Verification entry points\n\n`;
  if (checks.length) {
    const prefix = isWorkspace(module) ? `pnpm --filter ${pkg.name}` : `pnpm --dir ${module.path}`;
    content += `Declared scripts; inspect their configuration and prerequisites before running:\n\n`
      + checks.map((name) => `- \`${prefix} ${name}\``).join('\n') + '\n\n';
  } else {
    content += 'No standalone typecheck, test or lint script is declared here. Use the evidence above and the owning app or consumer checks.\n\n';
  }
  content += `Record the exact checks, date and result with the change. Update this card through ${link(file, `${outputRoot}/catalog.json`, 'catalog.json')}; see ${link(file, `${outputRoot}/README.md`, 'map maintenance')}.\n`;
  write(file, content);
}

const dirNames = (directory) => readdirSync(path.join(root, directory), { withFileTypes: true })
  .filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort();
const domainRoots = { lib: 'apps/storefront/src/lib', routes: 'apps/storefront/src/app' };
const classified = { lib: new Set(), routes: new Set() };
const domainIds = new Set();
for (const domain of catalog.storefrontDomains) {
  if (!/^[a-z0-9-]+$/.test(domain.id) || domainIds.has(domain.id)) fail(`Invalid or duplicate domain id: ${domain.id}`);
  for (const key of ['label', 'purpose']) {
    if (typeof domain[key] !== 'string' || !domain[key].trim()) fail(`Missing ${key}: storefront domain ${domain.id}`);
  }
  domainIds.add(domain.id);
  const file = `${outputRoot}/storefront/${domain.id}.md`;
  let content = header(domain.label)
    + `${link(file, `${outputRoot}/storefront/README.md`, 'Storefront domains')} · ${link(file, `${outputRoot}/apps/storefront.md`, 'Storefront module')}\n\n`
    + `${domain.purpose}\n\n`
    + `**Progress:** source grouping reviewed ${catalog.reviewedOn}. The directory roots below exist; individual features can be available, retired, paused or incomplete. This inventory does not validate route behavior or deployed availability.\n\n`
    + `**Next review:** follow the owning route into its library, check the current policy and existing tests, and record a dated result with the change. ${sourceLink(file, 'apps/storefront/docs/commercial-retirement.md', 'The commerce boundary')} applies to all domains.\n\n`;
  for (const [kind, directory] of Object.entries(domainRoots)) {
    if (!Array.isArray(domain[kind])) { fail(`Missing ${kind} list: ${domain.id}`); continue; }
    content += `## ${kind === 'lib' ? 'Domain libraries' : 'Route families'}\n\n`;
    for (const entry of domain[kind]) {
      if (!safePath(entry) || entry.includes('/')) fail(`Invalid ${kind} directory: ${entry}`);
      if (classified[kind].has(entry)) fail(`Duplicate ${kind} classification: ${entry}`);
      classified[kind].add(entry);
      sourceExists(`${directory}/${entry}`);
      content += `- ${sourceLink(file, `${directory}/${entry}`, entry)}\n`;
    }
    content += '\n';
  }
  if (domain.evidence) {
    if (!Array.isArray(domain.evidence) || !domain.evidence.length) fail(`Invalid evidence: storefront domain ${domain.id}`);
    else {
      domain.evidence.forEach(sourceExists);
      content += '## Connection evidence\n\n' + domain.evidence.map((entry) => `- ${sourceLink(file, entry)}`).join('\n') + '\n\n';
    }
  }
  content += 'Route families include their nested pages and handlers. A filesystem route can be an API, redirect or paused surface; the directory name alone does not promise a visitor feature.\n';
  write(file, content);
}
for (const [kind, directory] of Object.entries(domainRoots)) {
  const actual = new Set(dirNames(directory));
  for (const name of actual) if (!classified[kind].has(name)) fail(`Unclassified storefront ${kind} directory: ${name}`);
  for (const name of classified[kind]) if (!actual.has(name)) fail(`Missing storefront ${kind} directory: ${name}`);
}

const storefrontIndex = `${outputRoot}/storefront/README.md`;
let storefrontContent = header('Storefront domain map')
  + `${link(storefrontIndex, `${outputRoot}/README.md`, 'All modules')} · ${link(storefrontIndex, `${outputRoot}/apps/storefront.md`, 'Storefront purpose and progress')}\n\n`
  + `Choose the area you want to understand. These groups cover every immediate directory in src/lib and src/app, including historical and paused routes. They organize existing code without moving imports or routes.\n\n`
  + `| Area | Purpose |\n|---|---|\n`
  + catalog.storefrontDomains.map((domain) => `| ${link(storefrontIndex, `${outputRoot}/storefront/${domain.id}.md`, domain.label)} | ${escapeCell(domain.purpose)} |`).join('\n')
  + '\n\n## Existing sources of truth\n\n'
  + [
    ['apps/storefront/src/lib/manifest.ts', 'Manifest: reviewed endpoints, authentication and modalities'],
    ['apps/storefront/src/lib/graph.ts', 'Graph: derived resource and meaning relationships'],
    ['apps/storefront/src/lib/nav/menu-config.ts', 'Navigation: website menu definitions'],
    ['apps/storefront/src/lib/agent-tools-catalog.ts', 'Tool catalog: machine tool discovery'],
    ['apps/storefront/src/lib/game/registry-bootstrap.ts', 'Game registry: engine registration'],
    ['apps/storefront/src/lib/lifecycle/registry.ts', 'Lifecycle registry: host binding for shared journey slots'],
  ].map(([file, label]) => `- ${sourceLink(storefrontIndex, file, label)}`).join('\n')
  + '\n\nUse these registries for their own contracts. The module map is an orientation and progress record; it does not replace them with a second endpoint registry.\n\n'
  + '## Top-level files\n\n'
  + 'These files sit outside the domain directories. This inventory is derived from their filenames; use their source comments and imports to establish their role. Test files remain beside their subjects.\n\n';
for (const [kind, directory] of Object.entries(domainRoots)) {
  const files = readdirSync(path.join(root, directory), { withFileTypes: true }).filter((entry) => entry.isFile() && !/\.(test|spec)\./.test(entry.name)).map((entry) => entry.name).sort();
  storefrontContent += `### ${kind === 'lib' ? 'Shared library files' : 'Application entry and layout files'}\n\n`
    + files.map((entry) => `- ${sourceLink(storefrontIndex, `${directory}/${entry}`, entry)}`).join('\n') + '\n\n';
}
write(storefrontIndex, storefrontContent.trimEnd() + '\n');

const index = `${outputRoot}/README.md`;
const workspaceCount = catalog.modules.filter(isWorkspace).length;
const extensionCount = catalog.modules.filter((module) => !packageInfo.has(module.path)).length;
const nestedCount = catalog.modules.length - workspaceCount - extensionCount;
let indexContent = header('Module map')
  + `${link(index, 'README.md', 'Project entry')} · ${link(index, 'docs/README.md', 'Documentation')} · ${link(index, 'docs/agents/README.md', 'Agent guide')}\n\n`
  + `Find a module's purpose, source, scope, recorded progress and next review. This map covers **${catalog.modules.length} module roots**: ${workspaceCount} pnpm workspace packages, ${extensionCount} extension${extensionCount === 1 ? '' : 's'} without package.json, and ${nestedCount} nested support packages. Source review: **${catalog.reviewedOn}**.\n\n`
  + `**Start with the website:** ${link(index, storefrontIndex, 'Storefront domains')} groups ${classified.lib.size} library directories and ${classified.routes.size} route families by purpose.\n\n`
  + `**Current boundary:** ${sourceLink(index, 'apps/storefront/docs/commercial-retirement.md', 'New paid commerce is retired')}. Retained source can support existing agreements, a preview, a paused feature or historical compatibility. Presence in this map is not a release or service-health claim.\n\n`;
for (const [group, title] of Object.entries(groups)) {
  indexContent += `## ${title}\n\n| Module | Purpose |\n|---|---|\n`
    + catalog.modules.filter((module) => module.group === group).map((module) => `| ${link(index, cardPath(module), module.label)} | ${escapeCell(module.purpose)} |`).join('\n') + '\n\n';
}
indexContent += '## How the pieces connect\n\n'
  + 'The storefront is the main visitor and operator application. Wholesale retains its research and existing-order responsibilities. RewardsPro owns its current loyalty platform and extensions; RewardsPro API is a separate backend foundation. Shared packages hold reusable contracts and domain logic. Nested tools support their owning app.\n\n'
  + 'Each module card derives declared dependency and consumer links from package.json. The storefront domain guide links the existing runtime registries. Those two views cover different questions: package composition and public interfaces. Neither is a claim that every listed path executes in production.\n\n'
  + '## Record progress and keep the map current\n\n'
  + `1. Edit the relevant record in ${link(index, `${outputRoot}/catalog.json`, 'catalog.json')}: purpose, scope, evidence, progress and next review. Update reviewedOn for a full inventory review; use explicit dates in progress for individual changes. Record completed checks and remaining work with evidence, without completion percentages.\n`
  + '2. Add new package or extension roots to modules. Add new storefront library or route-root directories to one storefrontDomains group; keep source paths in their existing locations.\n'
  + '3. Run `pnpm docs:modules` to regenerate these pages, then `pnpm audit:modules` to check coverage, evidence paths, declared dependencies and generated output. These commands use only local source files and Git filenames; they load no app code or credentials and make no network calls.\n'
  + '4. Run the checks appropriate to the code change and record their actual result. The map audit checks documentation structure; it does not run module tests, verify policy behavior or contact services.\n\n'
  + `The ${link(index, `${outputRoot}/catalog.json`, 'catalog')} is the authored record; Markdown cards are generated views. Existing app READMEs, ${link(index, 'docs/missions/README.md', 'mission cards')} and ${link(index, 'docs/handoffs/README.md', 'handoffs')} retain detailed plans and dated results. Link them instead of copying their task queues.\n\n`
  + 'The coverage boundary is package/extension roots and immediate storefront domain directories. Nested implementation files are reached through those directories; this is not an exhaustive function inventory. Planned packages without source manifests remain in their original plans until implementation exists.\n';
write(index, indexContent);

// Check all generated relative links, including navigation links outside the
// catalog's evidence lists. Outputs need not exist yet during --write.
for (const [file, content] of outputFiles) {
  for (const match of content.matchAll(/\[[^\]]+\]\(([^)]+)\)/g)) {
    const target = match[1].split('#')[0];
    if (!target || /^[a-z]+:/i.test(target)) continue;
    const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(file), target));
    if (!safePath(resolved) || (!outputFiles.has(resolved) && !existsSync(path.join(root, resolved)))) {
      fail(`Broken generated link: ${file} -> ${target}`);
    }
  }
}

// Do not silently delete old cards: surface stale generated paths for review.
const existingGenerated = (directory) => {
  if (!existsSync(path.join(root, directory))) return;
  for (const entry of readdirSync(path.join(root, directory), { withFileTypes: true })) {
    const file = `${directory}/${entry.name}`;
    if (entry.isDirectory()) existingGenerated(file);
    else if (entry.name.endsWith('.md') && read(file).startsWith('<!-- Generated by scripts/module-map.mjs;') && !outputFiles.has(file)) fail(`Obsolete generated page requires review: ${file}`);
  }
};
existingGenerated(outputRoot);
if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}
let stale = 0;
for (const [file, content] of outputFiles) {
  const full = path.join(root, file);
  if (mode === '--write') {
    mkdirSync(path.dirname(full), { recursive: true });
    if (!existsSync(full) || read(file) !== content) writeFileSync(full, content);
  } else if (!existsSync(full) || read(file) !== content) {
    console.error(`Stale generated page: ${file}`);
    stale++;
  }
}
if (stale) {
  console.error('Run pnpm docs:modules after updating catalog.json.');
  process.exit(1);
}
console.log(`Module map ${mode === '--write' ? 'generated' : 'verified'}: ${catalog.modules.length} modules (${workspaceCount} workspace), ${catalog.storefrontDomains.length} storefront domains, ${outputFiles.size} pages. Source evidence only; no runtime or network checks.`);
